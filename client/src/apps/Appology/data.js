/**
 * Merge user custom config over default apology data
 * @param {Object} customConfig User customized configuration object
 * @returns {Object} Complete merged config object
 */
export function getMergedApologyData(customConfig = {}) {
  const themeSlug = customConfig.themeSlug || customConfig.selectedTheme || customConfig.theme || 'midnight-romance';

  return {
    ...DEFAULT_APOLOGY_DATA,
    ...customConfig,
    themeSlug,
    // Preserve custom arrays if present
    handwrittenNotes: customConfig.handwrittenNotes && customConfig.handwrittenNotes.length > 0
      ? customConfig.handwrittenNotes
      : DEFAULT_APOLOGY_DATA.handwrittenNotes,
    promises: customConfig.promises && customConfig.promises.length > 0
      ? customConfig.promises
      : DEFAULT_APOLOGY_DATA.promises,
    chapters: customConfig.chapters && customConfig.chapters.length > 0
      ? customConfig.chapters
      : customConfig.memories && customConfig.memories.length > 0
        ? customConfig.memories
        : DEFAULT_APOLOGY_DATA.chapters,
    futureChanges: customConfig.futureChanges && customConfig.futureChanges.length > 0
      ? customConfig.futureChanges
      : DEFAULT_APOLOGY_DATA.futureChanges
  };
}
